package com.studymatch.exceptions;

import org.springframework.http.HttpStatus;

public enum ErrorCode {

  VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
  NOT_FOUND(HttpStatus.NOT_FOUND),
  UNAUTHENTICATED(HttpStatus.UNAUTHORIZED),
  INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),
  ACCOUNT_BLOCKED(HttpStatus.FORBIDDEN),
  ACCESS_DENIED(HttpStatus.FORBIDDEN),
  CSRF_TOKEN_INVALID(HttpStatus.FORBIDDEN),
  PASSWORD_CHANGE_REQUIRED(HttpStatus.FORBIDDEN),
  PERSONALITY_TEST_REQUIRED(HttpStatus.FORBIDDEN),
  CURRENT_PASSWORD_INCORRECT(HttpStatus.BAD_REQUEST),
  NEW_PASSWORD_SAME_AS_CURRENT(HttpStatus.BAD_REQUEST),
  PASSWORD_TOO_LONG(HttpStatus.BAD_REQUEST),
  RESET_CODE_INVALID(HttpStatus.BAD_REQUEST),
  INSTITUTIONAL_EMAIL_ALREADY_EXISTS(HttpStatus.CONFLICT),
  AT_LEAST_ONE_LANGUAGE_REQUIRED(HttpStatus.BAD_REQUEST),
  INVALID_BANNER(HttpStatus.BAD_REQUEST),
  STATUTE_END_DATE_IN_PAST(HttpStatus.BAD_REQUEST),
  SUBJECT_ALREADY_IN_DEGREE(HttpStatus.CONFLICT),
  AT_LEAST_ONE_TEACHER_REQUIRED(HttpStatus.BAD_REQUEST),
  CLASS_SECTION_ALREADY_EXISTS(HttpStatus.CONFLICT),
  CLASS_SECTION_NOT_IN_SUBJECT_EDITION(HttpStatus.BAD_REQUEST),
  GROUP_WORK_NOT_ALLOWED_FOR_EXAMS(HttpStatus.BAD_REQUEST),
  INVALID_GROUP_SIZES(HttpStatus.BAD_REQUEST),
  SEPARATION_SAME_STUDENT(HttpStatus.BAD_REQUEST),
  SEPARATION_ALREADY_EXISTS(HttpStatus.CONFLICT),
  ASSIGNMENT_NOT_GROUP_WORK(HttpStatus.BAD_REQUEST),
  APPLICATION_ALREADY_DECIDED(HttpStatus.CONFLICT),
  STUDYROOM_CLOSED(HttpStatus.CONFLICT),
  STUDYROOM_ALREADY_STARTED(HttpStatus.CONFLICT),
  STUDYROOM_IN_PAST(HttpStatus.BAD_REQUEST),
  STUDYROOM_ENDS_BEFORE_START(HttpStatus.BAD_REQUEST),
  STUDYROOM_NOT_ENDED(HttpStatus.CONFLICT),
  STUDYROOM_FULL(HttpStatus.CONFLICT),
  TUTOR_CANNOT_JOIN_OWN_STUDYROOM(HttpStatus.FORBIDDEN),
  ALREADY_JOINED_STUDYROOM(HttpStatus.CONFLICT),
  NOT_A_PARTICIPANT(HttpStatus.FORBIDDEN),
  CAPACITY_BELOW_PARTICIPANTS(HttpStatus.CONFLICT),
  ATTENDANCE_NOT_CONFIRMED(HttpStatus.FORBIDDEN),
  RATING_WINDOW_CLOSED(HttpStatus.CONFLICT);

  private final HttpStatus status;

  ErrorCode(HttpStatus status) {
    this.status = status;
  }

  public HttpStatus getStatus() {
    return status;
  }
}
